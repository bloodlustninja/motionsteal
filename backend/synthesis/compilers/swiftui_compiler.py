"""
SwiftUI Compiler - Generates .swift Views
"""

from typing import Dict, List, Optional


class SwiftUICompiler:
    """Compiles animation specs into SwiftUI code."""

    def __init__(self):
        """Initialize SwiftUI compiler."""
        pass

    def compile_animation(
        self,
        phases: List[Dict],
        fit_type: str,
        metrics: Dict,
        design_tokens: Optional[Dict] = None
    ) -> str:
        """Compile animation into SwiftUI code."""
        tokens = design_tokens or self._default_tokens()
        
        if fit_type == "spring":
            anim_spec = f".spring(response: {metrics.get('damping_ratio', 0.7)}, dampingFraction: {metrics.get('damping_ratio', 0.7) / 2})"
        else:
            handles = metrics.get('handles', [0.25, 0.1, 0.25, 1.0])
            anim_spec = f".easeInOut(CurveBezier(x1: {handles[0]}, y1: {handles[1]}, x2: {handles[2]}, y2: {handles[3]}))"

        code = f"""// Auto-generated by MotionForge
import SwiftUI

struct FluidUIAnimation: View {{
    @State private var expanded = false

    var body: some View {{
        ZStack {{
            Rectangle()
                .fill(Color(hex: "{tokens['colors']['background']}"))
                .frame(height: 200)
                .cornerRadius({tokens['corner_radius']})
            
            RoundedRectangle(cornerRadius: 12)
                .fill(expanded ? Color(hex: "{tokens['colors']['primary']}") : Color(hex: "{tokens['colors']['secondary']}"))
                .frame(width: 100 + (expanded ? 200 : 0), height: 100)
                .offset(x: expanded ? 50 : 0, y: expanded ? 50 : 0)
                .animation{anim_spec}, value: expanded)
                .overlay {{
                    if expanded {{
                        Image(systemName: "checkmark")
                            .foregroundColor(Color(hex: "{tokens['colors']['text']}"))
                            .transition(.opacity.combined(with: .scale))
                    }}
                }}
        }}
        .onTapGesture {{
            withAnimation {{ expanded.toggle() }}
        }}
    }}
}}

// Usage:
// FluidUIAnimation()
"""
        return code

    def _default_tokens(self) -> Dict:
        """Return default design tokens."""
        return {
            "colors": {
                "primary": "6366F1",
                "secondary": "8B5CF6",
                "background": "1A1A1A",
                "text": "FFFFFF"
            },
            "corner_radius": 16,
            "shadows": {},
            "typography": {},
            "icons": []
        }
