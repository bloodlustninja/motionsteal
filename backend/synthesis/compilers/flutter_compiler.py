"""
Flutter Compiler - Generates Dart widgets with SpringSimulation
Uses AnimatedBuilder with discrete state transitions.
"""

from typing import Dict, List, Optional


class FlutterCompiler:
    """Compiles animation specs into Flutter code."""

    def __init__(self):
        """Initialize Flutter compiler."""
        pass

    def compile_from_state_machine(
        self,
        state_machine: Dict,
        spring_preset: str = "Fluid"
    ) -> str:
        """Compile animation from state machine into Flutter code."""
        # Map preset to Flutter SpringDescription values
        preset_map = {
            "Snappy": {"stiffness": 420.0, "damping": 72.0},
            "Bouncy": {"stiffness": 300.0, "damping": 39.0},
            "Fluid": {"stiffness": 220.0, "damping": 33.0},
            "Gentle": {"stiffness": 140.0, "damping": 28.0}
        }
        
        preset = preset_map.get(spring_preset, preset_map["Fluid"])
        
        # Extract states
        idle_state = state_machine["states"]["idle"]
        apex_state = state_machine["states"]["apex"]
        settled_state = state_machine["states"]["settled"]
        
        component_type = state_machine.get("component_type", "Card")

        code = f"""// Auto-generated by MotionForge State-Diffing Engine
import 'package:flutter/material.dart';

enum ComponentState {{
  idle,
  apex,
  expanded
}}

class {component_type}Animation extends StatefulWidget {{
  const {{super.key}};

  @override
  State<{component_type}Animation> createState() => _{component_type}AnimationState();
}}

class _{component_type}AnimationState extends State<{component_type}Animation>
    with SingleTickerProviderStateMixin {{
  late AnimationController _controller;
  late Animation<double> _animation;
  ComponentState _currentState = ComponentState.idle;

  @override
  void initState() {{
    super.initState();
    _controller = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 400),
    );

    // Spring physics from design system preset
    _animation = CurvedAnimation(
      parent: _controller,
      curve: SpringSimulation(
        const SpringDescription(
          mass: 1.0,
          stiffness: {preset["stiffness"]},
          damping: {preset["damping"]},
        ),
        0.0,
        1.0,
        0.0,
      ),
    );
  }}

  @override
  void dispose() {{
    _controller.dispose();
    super.dispose();
  }}

  void _toggleState() {{
    setState(() {{
      if (_currentState == ComponentState.idle) {{
        _currentState = ComponentState.expanded;
        _controller.forward();
      }} else {{
        _currentState = ComponentState.idle;
        _controller.reverse();
      }}
    }});
  }}

  @override
  Widget build(BuildContext context) {{
    return GestureDetector(
      onTap: _toggleState,
      child: Container(
        width: double.infinity,
        height: 200,
        color: Color(0xFF{idle_state["background_color"]}),
        child: AnimatedBuilder(
          animation: _animation,
          builder: (context, child) {{
            final double animationValue = _animation.value;

            // Interpolate properties based on state
            final double width = _interpolate(
              animationValue,
              {idle_state["width_dp"]}.0,
              {settled_state["width_dp"]}.0,
            );
            final double height = _interpolate(
              animationValue,
              {idle_state["height_dp"]}.0,
              {settled_state["height_dp"]}.0,
            );
            final double offsetY = _interpolate(
              animationValue,
              {idle_state["offset_y_dp"]}.0,
              {settled_state["offset_y_dp"]}.0,
            );
            final double scale = _interpolate(
              animationValue,
              {idle_state["scale"]},
              {settled_state["scale"]},
            );

            return Center(
              child: Container(
                width: width,
                height: height,
                decoration: BoxDecoration(
                  color: Color.lerp(
                    Color(0xFF{idle_state["background_color"]}),
                    Color(0xFF{settled_state["background_color"]}),
                    animationValue,
                  ),
                  borderRadius: BorderRadius.circular({idle_state["corner_radius_dp"]}.0),
                ),
                transform: Matrix4.identity()
                  ..translate(0.0, offsetY)
                  ..scale(scale),
                child: _buildChildren(),
              ),
            );
          }},
        ),
      ),
    );
  }}

  double _interpolate(double t, double start, double end) {{
    return start + (end - start) * t;
  }}

  Widget _buildChildren() {{
    {self._generate_children_code(state_machine["staggered_children"])}
  }}

// Usage:
// {component_type}Animation()
"""

        return code

    def _generate_children_code(self, staggered_children: Dict) -> str:
        """Generate code for staggered child elements."""
        if not staggered_children.get("has_children", False):
            return "return null;"
        
        count = staggered_children.get("count", 0)
        child_type = staggered_children.get("child_type", "icon")
        
        if child_type == "icon":
            return f"""
    return Row(
      mainAxisAlignment: MainAxisAlignment.center,
      children: List.generate({count}, (index) {{
        return Icon(
          Icons.star,
          color: Colors.white,
          size: 24,
        );
      }}),
    );
"""
        else:
            return f"""
    return Row(
      mainAxisAlignment: MainAxisAlignment.center,
      children: List.generate({count}, (index) {{
        return Text(
          'Item ${{index + 1}}',
          style: TextStyle(color: Colors.white),
        );
      }}),
    );
"""

    def compile_animation(
        self,
        phases: List[Dict],
        fit_type: str,
        metrics: Dict,
        design_tokens: Optional[Dict] = None
    ) -> str:
        """Legacy method for backward compatibility."""
        return self.compile_from_state_machine(
            {
                "states": {
                    "idle": {"width_dp": 200, "height_dp": 100, "offset_y_dp": 0, "offset_x_dp": 0, "corner_radius_dp": 12, "alpha": 1.0, "scale": 1.0, "rotation_deg": 0.0, "background_color": "#1A1A1A", "elevation_dp": 2},
                    "apex": {"width_dp": 220, "height_dp": 110, "offset_y_dp": -10, "offset_x_dp": 0, "corner_radius_dp": 12, "alpha": 1.0, "scale": 1.1, "rotation_deg": 0.0, "background_color": "#6366F1", "elevation_dp": 4},
                    "settled": {"width_dp": 200, "height_dp": 100, "offset_y_dp": 0, "offset_x_dp": 0, "corner_radius_dp": 12, "alpha": 1.0, "scale": 1.0, "rotation_deg": 0.0, "background_color": "#1A1A1A", "elevation_dp": 2}
                },
                "staggered_children": {"has_children": False, "count": 0, "delay_step_ms": 0, "child_type": "icon"},
                "transition_type": "expand",
                "component_type": "Card"
            },
            "Fluid"
        )
