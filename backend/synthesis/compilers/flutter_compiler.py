"""
Flutter Compiler - Generates Dart widgets with SpringSimulation
"""

from typing import Dict, List, Optional


class FlutterCompiler:
    """Compiles animation specs into Flutter code."""

    def __init__(self):
        """Initialize Flutter compiler."""
        pass

    def compile_animation(
        self,
        phases: List[Dict],
        fit_type: str,
        metrics: Dict,
        design_tokens: Optional[Dict] = None
    ) -> str:
        """Compile animation into Flutter code."""
        tokens = design_tokens or self._default_tokens()
        
        if fit_type == "spring":
            omega = metrics.get('omega', 15)
            zeta = metrics.get('zeta', 0.7)
            damping = 2 * zeta * omega
            spring_spec = f"SpringSimulation(\n  SpringDescription(\n    mass: 1.0,\n    stiffness: {metrics.get('stiffness', 300)},\n    damping: {damping}\n  ),\n  0.0,\n  1.0,\n  0.0\n)"
        else:
            handles = metrics.get('handles', [0.25, 0.1, 0.25, 1.0])
            spring_spec = f"CurvedAnimation(\n  parent: _controller,\n  curve: const Cubic({handles[0]}, {handles[1]}, {handles[2]}, {handles[3]})\n)"

        code = f"""// Auto-generated by MotionForge
import 'package:flutter/material.dart';

class FluidUIAnimation extends StatefulWidget {{
  const FluidUIAnimation({{super.key}});

  @override
  State<FluidUIAnimation> createState() => _FluidUIAnimationState();
}}

class _FluidUIAnimationState extends State<FluidUIAnimation>
    with SingleTickerProviderStateMixin {{
  late AnimationController _controller;
  late Animation<double> _animation;
  bool _expanded = false;

  @override
  void initState() {{
    super.initState();
    _controller = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: {int(phases[-1]['end_t'] * 1000) if phases else 300}),
    );

    _animation = CurvedAnimation(
      parent: _controller,
      curve: {spring_spec},
    );
  }}

  @override
  void dispose() {{
    _controller.dispose();
    super.dispose();
  }}

  void _toggle() {{
    setState(() {{
      _expanded = !_expanded;
    }});
    if (_expanded) {{
      _controller.forward();
    }} else {{
      _controller.reverse();
    }}
  }}

  @override
  Widget build(BuildContext context) {{
    return GestureDetector(
      onTap: _toggle,
      child: Container(
        width: double.infinity,
        height: 200,
        decoration: BoxDecoration(
          color: Color(0xFF{tokens['colors']['background']}),
          borderRadius: BorderRadius.circular({tokens['corner_radius']}.0),
        ),
        child: AnimatedBuilder(
          animation: _animation,
          builder: (context, child) {{
            return Positioned(
              left: 50 * _animation.value,
              top: 50 * _animation.value,
              child: Container(
                width: 100 + 200 * _animation.value,
                height: 100,
                decoration: BoxDecoration(
                  color: Color.lerp(
                    Color(0xFF{tokens['colors']['secondary']}),
                    Color(0xFF{tokens['colors']['primary']}),
                    _animation.value,
                  ),
                  borderRadius: BorderRadius.circular(12.0),
                ),
                child: _expanded
                    ? Icon(
                        Icons.check,
                        color: Color(0xFF{tokens['colors']['text']}),
                      )
                    : null,
              ),
            );
          }},
        ),
      ),
    );
  }}
}}

// Usage:
// FluidUIAnimation()
"""
        return code

    def _default_tokens(self) -> Dict:
        """Return default design tokens."""
        return {
            "colors": {
                "primary": "6366F1",
                "secondary": "8B5CF6",
                "background": "1A1A1A",
                "text": "FFFFFF"
            },
            "corner_radius": 16,
            "shadows": {},
            "typography": {},
            "icons": []
        }
