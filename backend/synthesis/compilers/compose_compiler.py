"""
Jetpack Compose Compiler - Generates Complete .kt Composables
"""

from typing import Dict, List, Optional


class ComposeCompiler:
    """Compiles animation specs into Jetpack Compose code."""

    def __init__(self):
        """Initialize Compose compiler."""
        pass

    def compile_animation(
        self,
        phases: List[Dict],
        fit_type: str,
        metrics: Dict,
        design_tokens: Optional[Dict] = None
    ) -> str:
        """
        Compile animation into Jetpack Compose code.
        
        Args:
            phases: Animation phases
            fit_type: Type of fit ('spring' or 'bezier')
            metrics: Fitted parameters
            design_tokens: Design tokens from token extractor
            
        Returns:
            Complete Compose code string
        """
        tokens = design_tokens or self._default_tokens()
        
        # Generate animation spec
        if fit_type == "spring":
            anim_spec = f"spring(\n    dampingRatio = {metrics.get('damping_ratio', 0.7)}f,\n    stiffness = {metrics.get('stiffness', 300)}f\n)"
        else:
            handles = metrics.get('handles', [0.25, 0.1, 0.25, 1.0])
            anim_spec = f"tween(\n    durationMillis = {int(phases[-1]['end_t'] * 1000) if phases else 300},\n    easing = CubicBezierEasing({handles[0]}f, {handles[1]}f, {handles[2]}f, {handles[3]}f)\n)"

        code = f"""// Auto-generated by MotionForge
package com.motionforge.example

import androidx.compose.animation.*
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

@Composable
fun FluidUIAnimation(
    modifier: Modifier = Modifier
) {{
    var expanded by remember {{ mutableStateOf(false) }}

    val state by animateFloatAsState(
        targetValue = if (expanded) 1f else 0f,
        animationSpec = {anim_spec},
        label = "fluid_animation"
    )

    Box(
        modifier = modifier
            .fillMaxWidth()
            .height(200.dp)
            .background(Color(0xFF{tokens['colors']['background'].lstrip('#')}))
            .clip(RoundedCornerShape({tokens['corner_radius']}))
    ) {{
        // Animated element
        Box(
            modifier = Modifier
                .width((100 + state * 200).dp)
                .height(100.dp)
                .offset(
                    x = (state * 50).dp,
                    y = (state * 50).dp
                )
                .background(
                    if (expanded)
                        Color(0xFF{tokens['colors']['primary'].lstrip('#')})
                    else
                        Color(0xFF{tokens['colors']['secondary'].lstrip('#')})
                )
                .clip(RoundedCornerShape(12.dp))
        ) {{
            // Icon visibility
            AnimatedVisibility(
                visible = expanded,
                enter = fadeIn() + scaleIn(),
                exit = fadeOut() + scaleOut()
            ) {{
                Icon(
                    imageVector = Icons.Default.Check,
                    contentDescription = null,
                    tint = Color(0xFF{tokens['colors']['text'].lstrip('#')}),
                    modifier = Modifier
                        .size(24.dp)
                        .align(Alignment.Center)
                )
            }}
        }}
    }}
}}

// Usage:
// FluidUIAnimation(modifier = Modifier.padding(16.dp))
"""
        return code

    def _default_tokens(self) -> Dict:
        """Return default design tokens."""
        return {
            "colors": {
                "primary": "6366F1",
                "secondary": "8B5CF6",
                "background": "1A1A1A",
                "text": "FFFFFF"
            },
            "corner_radius": 16,
            "shadows": {},
            "typography": {},
            "icons": []
        }


def generate_compose_component(
    phases: List[Dict],
    fit_type: str,
    metrics: Dict,
    design_tokens: Optional[Dict] = None
) -> str:
    """
    Generate complete Jetpack Compose component.
    
    Args:
        phases: Animation phases
        fit_type: Fit type
        metrics: Metrics
        design_tokens: Design tokens
        
    Returns:
        Compose code string
    """
    compiler = ComposeCompiler()
    return compiler.compile_animation(phases, fit_type, metrics, design_tokens)
